export function dictForLocale(locale) {
  if (locale === 'be-tarask') return translations.beTarask;
  return translations[locale] || translations.ru;
}

export function translate(locale, keyPath, vars) {
  const d = dictForLocale(locale);
  const parts = keyPath.split('.');
  let cur = d;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in cur) cur = cur[p];
    else return applyVars(keyPath, vars);
  }
  return applyVars(typeof cur === 'string' ? cur : keyPath, vars);
}
